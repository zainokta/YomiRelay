func TestInstallRefusesGameDirectorySymlinkOutsideInstall(t *testing.T) {
	install := t.TempDir()
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(install, "game")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	game := games.Game{AppID: "111", Name: "Game", InstallPath: install, Engine: "renpy"}
	if err := (Manager{}).Install(game); !errors.Is(err, ErrUnsafePath) {
		t.Fatalf("Install error = %v, want ErrUnsafePath", err)
	}
	if _, err := os.Stat(filepath.Join(outside, "_yomirelay_hook.rpy")); !os.IsNotExist(err) {
		t.Fatal("hook was created through game symlink")
	}
}

func TestInstallRefusesHookSymlink(t *testing.T) {
	game := testGame(t)
	path := filepath.Join(game.InstallPath, "game", "_yomirelay_hook.rpy")
	outside := filepath.Join(t.TempDir(), "outside.rpy")
	if err := os.WriteFile(outside, []byte("untouched"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, path); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if err := (Manager{}).Install(game); !errors.Is(err, ErrUnsafePath) {
		t.Fatalf("Install error = %v, want ErrUnsafePath", err)
	}
	got, _ := os.ReadFile(outside)
	if string(got) != "untouched" {
		t.Fatal("hook symlink target was modified")
	}
}

func testGame(t *testing.T) games.Game {
	t.Helper()
	install := t.TempDir()
	if err := os.Mkdir(filepath.Join(install, "game"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(install, "renpy"), 0o755); err != nil {
		t.Fatal(err)
	}
	return games.Game{AppID: "111", Name: "Game", InstallPath: install, Engine: "renpy"}
}
